"""SLANet / PP-Structure table structure recognition adapter.
"""
from __future__ import annotations

import re
from typing import Any, Optional
import numpy as np
from PIL import Image

from .base import BaseTableExtractor, BoundingBox, RawCell, RawTable


class SLANetTableExtractor(BaseTableExtractor):
    """Runs Baidu SLANet (via RapidTable ONNX) on cropped table regions."""

    def __init__(self):
        self._engine = None

    def _ensure_loaded(self) -> None:
        if self._engine is None:
            from rapid_table import RapidTable
            self._engine = RapidTable()

    def _parse_html_table(self, html_str: str) -> tuple[list[str], list[list[str]]]:
        """Parses simple HTML table string generated by SLANet into headers and rows."""
        # Clean HTML
        rows_match = re.findall(r"<tr>(.*?)</tr>", html_str, re.DOTALL | re.IGNORECASE)
        if not rows_match:
            return [], []

        table_data = []
        for r_str in rows_match:
            cells = re.findall(r"<t[dh][^>]*>(.*?)</t[dh]>", r_str, re.DOTALL | re.IGNORECASE)
            # Clean cell text
            cleaned_cells = [re.sub(r"<[^>]+>", "", c).strip() for c in cells]
            table_data.append(cleaned_cells)

        if not table_data:
            return [], []

        header = table_data[0] if table_data else []
        rows = table_data[1:] if len(table_data) > 1 else []
        return header, rows

    def extract_tables_from_page(
        self,
        fitz_page: Any,
        page_index: int,
        page_image: Optional[Image.Image] = None,
        layout_regions: Optional[list[Any]] = None,
        candidate_bboxes: Optional[list[BoundingBox]] = None,
    ) -> list[RawTable]:
        if page_image is None:
            return []

        self._ensure_loaded()
        if self._engine is None:
            return []

        # Candidate bboxes to evaluate
        bboxes: list[BoundingBox] = []
        if candidate_bboxes:
            bboxes = candidate_bboxes
        elif layout_regions:
            for reg in layout_regions:
                if getattr(reg, "kind", "") == "table":
                    bboxes.append(reg.bbox)

        tables: list[RawTable] = []
        img_w, img_h = page_image.size
        pdf_w, pdf_h = float(fitz_page.rect.width), float(fitz_page.rect.height)
        scale_x = img_w / pdf_w if pdf_w > 0 else 1.0
        scale_y = img_h / pdf_h if pdf_h > 0 else 1.0

        for t_idx, bbox in enumerate(bboxes):
            px0 = max(0, int(bbox.x0 * scale_x) - 5)
            py0 = max(0, int(bbox.y0 * scale_y) - 5)
            px1 = min(img_w, int(bbox.x1 * scale_x) + 5)
            py1 = min(img_h, int(bbox.y1 * scale_y) + 5)

            if px1 <= px0 or py1 <= py0:
                continue

            crop = page_image.crop((px0, py0, px1, py1))
            crop_np = np.array(crop)

            try:
                res = self._engine(crop_np)
                pred_html = res.pred_htmls[0] if (res.pred_htmls and len(res.pred_htmls) > 0) else ""
                header, rows = self._parse_html_table(pred_html)

                # Extract cell bboxes
                raw_cells: list[RawCell] = []
                if res.cell_bboxes and len(res.cell_bboxes) > 0:
                    for cbox in res.cell_bboxes[0]:
                        # cbox is 8-coords [x0,y0, x1,y1, x2,y2, x3,y3]
                        cx0 = float(min(cbox[0], cbox[6]))
                        cy0 = float(min(cbox[1], cbox[3]))
                        cx1 = float(max(cbox[2], cbox[4]))
                        cy1 = float(max(cbox[5], cbox[7]))

                        page_cx0 = bbox.x0 + (cx0 / scale_x)
                        page_cy0 = bbox.y0 + (cy0 / scale_y)
                        page_cx1 = bbox.x0 + (cx1 / scale_x)
                        page_cy1 = bbox.y0 + (cy1 / scale_y)

                        raw_cells.append(
                            RawCell(
                                row_idx=0,
                                col_idx=0,
                                bbox=BoundingBox(page_cx0, page_cy0, page_cx1, page_cy1),
                            )
                        )

                tables.append(
                    RawTable(
                        table_id=f"t-p{page_index}-{t_idx:02d}",
                        page_index=page_index,
                        bbox=bbox,
                        header=header,
                        rows=rows,
                        cells=raw_cells,
                        source="slanet_ppstructure",
                        confidence=0.92,
                    )
                )
            except Exception:
                pass

        return tables
